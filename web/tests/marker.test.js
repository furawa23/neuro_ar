import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { inflateSync } from 'node:zlib';
import toolkit from '@ar-js-org/artoolkit5-js';
import { coverProjection, createPatternText, PATTERN_RATIO, MARKER_WIDTH_MILLIMETERS, POSE_METERS_PER_UNIT } from '../src/ar/marker-math.js';

test('cover projection agrees with the CSS central crop in portrait and landscape', () => {
  // Projected source points are independently transformed from pixels to the
  // viewport, so the test covers principal-point offsets as well as scale.
  const base = [1.9, 0, 0, 0, 0, 2.5, 0, 0, -0.012, -0.008, -1, -1, 0, 0, -0.02, 0];
  for (const [vw, vh, sw, sh] of [[640, 480, 390, 600], [480, 640, 900, 420], [640, 480, 640, 480]]) {
    const actual = coverProjection(base, vw, vh, sw, sh);
    const scale = Math.max(sw / vw, sh / vh);
    for (const [x, y, z] of [[0, 0, -1], [0.1, 0.2, -0.5], [-0.3, 0.1, -1.2]]) {
      const nx = (base[0] * x + base[8] * z) / -z;
      const ny = (base[5] * y + base[9] * z) / -z;
      const sourceX = (nx + 1) * vw / 2;
      const sourceY = (1 - ny) * vh / 2;
      const expectedX = (sourceX - vw / 2) * scale + sw / 2;
      const expectedY = (sourceY - vh / 2) * scale + sh / 2;
      const actualX = ((actual[0] * x + actual[8] * z) / -z + 1) * sw / 2;
      const actualY = (1 - (actual[5] * y + actual[9] * z) / -z) * sh / 2;
      assert.ok(Math.abs(expectedX - actualX) < 1e-10);
      assert.ok(Math.abs(expectedY - actualY) < 1e-10);
    }
  }
  assert.throws(() => coverProjection(base, 0, 480, 390, 600), RangeError);
});

function decodeGeneratedPng(bytes) {
  let offset = 8;
  let width;
  let height;
  const blocks = [];
  while (offset < bytes.length) {
    const length = bytes.readUInt32BE(offset);
    const type = bytes.toString('ascii', offset + 4, offset + 8);
    const data = bytes.subarray(offset + 8, offset + 8 + length);
    if (type === 'IHDR') {
      width = data.readUInt32BE(0);
      height = data.readUInt32BE(4);
      assert.equal(data[8], 8);
      assert.equal(data[9], 0); // grayscale, generated by the project's print script
    }
    if (type === 'IDAT') blocks.push(data);
    offset += length + 12;
  }
  const filtered = inflateSync(Buffer.concat(blocks));
  const pixels = new Uint8Array(width * height);
  for (let y = 0; y < height; y += 1) {
    assert.equal(filtered[y * (width + 1)], 0);
    pixels.set(filtered.subarray(y * (width + 1) + 1, (y + 1) * (width + 1)), y * width);
  }
  return { width, height, pixels };
}

function rasterPrintImage(image, rotation = 0) {
  const width = 640;
  const height = 480;
  const data = new Uint8ClampedArray(width * height * 4).fill(255);
  const size = 360;
  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      let u = (x + 0.5) / size;
      let v = (y + 0.5) / size;
      for (let r = 0; r < rotation; r += 1) [u, v] = [1 - v, u];
      const value = image.pixels[Math.min(image.height - 1, Math.floor(v * image.height)) * image.width
        + Math.min(image.width - 1, Math.floor(u * image.width))];
      const at = ((y + 60) * width + x + 140) * 4;
      data[at] = value;
      data[at + 1] = value;
      data[at + 2] = value;
    }
  }
  return { data };
}

test('the actual printable PNG is recognized by the production WASM tracker in all four rotations', async () => {
  const base = new URL('../public/markers/', import.meta.url);
  const [png, pattern, camera] = await Promise.all([
    readFile(new URL('neuroar-marker.png', base)),
    readFile(new URL('neuroar-marker.patt', base), 'utf8'),
    readFile(new URL('camera_para.dat', base)),
  ]);
  assert.equal(pattern, createPatternText());
  assert.equal(pattern.trim().split(/\s+/).length, 16 * 16 * 3 * 4);
  const image = decodeGeneratedPng(png);
  const controller = await toolkit.ARController.initWithDimensions(640, 480, new Uint8Array(camera), {
    canvas: { getContext: () => ({}) },
  });
  try {
    controller.setPatternDetectionMode(controller.artoolkit.AR_TEMPLATE_MATCHING_MONO);
    controller.setPattRatio(PATTERN_RATIO);
    controller.setThresholdMode(controller.artoolkit.AR_LABELING_THRESH_MODE_AUTO_OTSU);
    const markerId = await controller.loadMarker(pattern);
    assert.ok(markerId >= 0);
    controller.trackPatternMarkerId(markerId, MARKER_WIDTH_MILLIMETERS);
    let found = [];
    controller.addEventListener('getMarker', (event) => {
      if (event.data.marker.idPatt === markerId) found.push({
        confidence: event.data.marker.cfPatt,
        matrix: Array.from(event.data.matrixGL_RH),
      });
    });
    for (let rotation = 0; rotation < 4; rotation += 1) {
      found = [];
      controller.process(rasterPrintImage(image, rotation));
      assert.equal(found.length, 1, `printed marker rotation ${rotation}`);
      assert.ok(found[0].confidence > 0.9);
      assert.ok(found[0].matrix.every(Number.isFinite));
      // 14 cm spans 280 pixels; the default camera's fx is ~610 px.
      assert.ok(Math.abs(-found[0].matrix[14] * POSE_METERS_PER_UNIT - 0.305) < 0.025);
    }
    found = [];
    controller.process({ data: new Uint8ClampedArray(640 * 480 * 4).fill(255) });
    assert.equal(found.length, 0, 'blank paper must not be recognized');
  } finally {
    // The SDK posts its load event one tick after initialization.
    await new Promise((resolve) => setTimeout(resolve, 5));
    controller.dispose();
  }
});
